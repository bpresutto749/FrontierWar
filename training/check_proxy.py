#!/usr/bin/env python3
"""How well does a pool of opponents predict the hidden hill? For every recorded
final warrior (runs/, baselines/, the reference), score it at 100 rounds against the
pool and against the hidden hill, and report Pearson and Spearman correlations over
all warriors and over agent-level warriors (hidden score >= 0.30).

usage: check_proxy.py POOL_DIR [POOL_DIR ...]   (e.g. training/train_hill data/sparring data/sparring_small)
Writes results/proxy_check.md.
"""
import glob
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from arena import core  # noqa: E402

HILL = sorted((ROOT / "data" / "hill").glob("*.red"))


def ranks(x):
    order = sorted(range(len(x)), key=lambda i: x[i])
    r = [0] * len(x)
    for k, i in enumerate(order):
        r[i] = k
    return r


def main():
    pools = [Path(p) for p in sys.argv[1:]]
    files = [f for f in sorted(glob.glob(str(ROOT / "runs" / "**" / "run_*.red"), recursive=True))
             + sorted(glob.glob(str(ROOT / "runs" / "codeclash-ladder-2026-07" / "*.red")))
             + [str(ROOT / "data" / "reference_toxic.red")] + sorted(glob.glob(str(ROOT / "baselines" / "*.red")))
             if "aborted" not in f]
    srcs = [Path(f).read_text(errors="replace") for f in files]
    keep = [i for i, s in enumerate(srcs) if core.assemble(s)[0]]
    hidden = {i: core.hill_score(core.play_hill(srcs[i], HILL, 100)) for i in keep}
    md = ["# Proxy check (generated by training/check_proxy.py, 100 rounds)", "",
          "| pool | opponents | set | n | Pearson | Spearman |", "|---|---|---|---|---|---|"]
    for pool in pools:
        opp = sorted((ROOT / pool).glob("*.red"))
        vis = {i: core.hill_score(core.play_hill(srcs[i], opp, 100)) for i in keep}
        for label, sel in (("all warriors", keep), ("agent-level (hidden >= 0.30)", [i for i in keep if hidden[i] >= 0.30])):
            a, b = [vis[i] for i in sel], [hidden[i] for i in sel]
            md.append(f"| {pool} | {len(opp)} | {label} | {len(sel)} | {statistics.correlation(a, b):.3f} | "
                      f"{statistics.correlation(ranks(a), ranks(b)):.3f} |")
            print(md[-1], flush=True)
    (ROOT / "results" / "proxy_check.md").write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
